const vm=require('node:vm'),fs=require('node:fs'),assert=require('node:assert/strict');
let now=1000;const elements={};const element=()=>({dataset:{},classList:{toggle(){}},querySelectorAll(){return []},append(){},addEventListener(){},setAttribute(){},value:'',focus(){}});
const body=element();
const context=vm.createContext({document:{body,getElementById:id=>elements[id]??=element(),addEventListener(){},createElement:element},performance:{now:()=>now},Date,Math,setInterval(){},setTimeout(){},clearTimeout(){},fetch:()=>new Promise(()=>{}),confirm:()=>false});
vm.runInContext(fs.readFileSync('app.js','utf8'),context);
vm.runInContext("render({exitDeadline:61000,webhookReady:true,armAwayConfigured:true,armStayConfigured:true}); exitDisplay();",context);
assert.match(elements['exit-countdown'].textContent,/60s/);
now=8000;
vm.runInContext('render(status); exitDisplay();',context);
assert.match(elements['exit-countdown'].textContent,/53s/);
now=61000;
vm.runInContext('exitDisplay();',context);
assert.match(elements['exit-countdown'].textContent,/Verify armed state/);
console.log('Countdown redraw and expiry regression checks passed.');
const ready={fresh:true,state:'disarmed',liveDelayEnabled:true,doors:Object.fromEntries(['Back Door','Front Door','Garage Door'].map(name=>[name,{connected:true,position:'closed'}]))};
context.ready=ready;
vm.runInContext("unlockToken='test';liveObservation=ready;renderObservation(ready);",context);
assert.equal(elements['arm-away'].disabled,false);
vm.runInContext("liveObservation={...ready,state:'breached'}; renderObservation(liveObservation); render(status);",context);
assert.equal(elements['state'].textContent,'THERE HAS BEEN A BREACH');
assert.equal(elements['sleep-state'].textContent,'THERE HAS BEEN A BREACH');
assert.equal(elements['arm-away'].disabled,true);
vm.runInContext("liveObservation={fresh:false}; renderObservation(liveObservation);",context);
assert.equal(elements['state'].textContent,'Status unverified');
assert.equal(elements['arm-away'].disabled,true);
console.log('Confirmed-state rendering and incomplete-coverage checks passed.');

// Follow the real sequence, including a native breach during a pending entry delay.
vm.runInContext("acceptObservation({...ready,remaining:null});",context);
assert.equal(body.dataset.tone,'blue');
assert.equal(elements['standby-lock'].dataset.icon,'open');
vm.runInContext("acceptObservation({...ready,state:'arming',exitRemaining:60,remaining:null});",context);
assert.equal(elements['standby-display'].hidden,true);
assert.equal(elements['countdown-value'].textContent,'1:00');
assert.equal(body.dataset.alarmMode,'exit');
now+=7000;
vm.runInContext('render(status); exitDisplay();',context);
assert.equal(elements['countdown-value'].textContent,'0:53');
vm.runInContext("acceptObservation({...ready,state:'arming',exitRemaining:0,remaining:null});",context);
assert.equal(body.dataset.alarmMode,'exit');
assert.equal(elements['breach-display'].hidden,true,'Exit expiry must not report a breach');
vm.runInContext("acceptObservation({...ready,state:'armed',remaining:null});",context);
assert.equal(body.dataset.tone,'red');
assert.equal(elements['standby-display'].hidden,false);
assert.equal(elements['standby-lock'].dataset.icon,'closed');
vm.runInContext("acceptObservation({...ready,state:'breached',remaining:60,notification:'not_sent'});",context);
assert.equal(body.dataset.alarmMode,'entry');
assert.equal(elements['breach-display'].hidden,true,'Native breach must not hide a pending entry countdown');
vm.runInContext("show('pin-screen');",context);
assert.equal(elements['alert-strip'].hidden,false);
assert.equal(elements['strip-time'].textContent,'1:00');
vm.runInContext("acceptObservation({...ready,state:'breached',remaining:1,notification:'not_sent'});",context);
now+=1100;
vm.runInContext('exitDisplay();',context);
assert.equal(body.dataset.alarmMode,'breach');
assert.equal(elements['breach-display'].hidden,false);
assert.equal(elements['arm-away'].hidden,true);
vm.runInContext("acceptObservation({...ready,state:'armed',remaining:null,notification:'accepted'});",context);
assert.equal(body.dataset.alarmMode,'breach','Accepted expiry must stay visible until confirmed disarm');
vm.runInContext("acceptObservation({...ready,state:'unknown',fresh:false,remaining:null,notification:'accepted'});",context);
assert.equal(body.dataset.tone,'red','Lost connection must not imply disarmed');
vm.runInContext("acceptObservation({...ready,remaining:null,notification:'not_sent'}); lock();",context);
assert.equal(body.dataset.tone,'blue');
assert.equal(body.dataset.alarmMode,'disarmed');
assert.equal(elements['standby-display'].hidden,false);
assert.equal(elements['alarm-display'].hidden,true);
assert.equal(elements['standby-lock'].dataset.icon,'open');
assert.equal(elements['arm-away'].hidden,false);
assert.equal(elements['alert-strip'].hidden,true);
console.log('Exit, entry, breach, PIN-screen countdown, and confirmed-disarm presentation checks passed.');

// An accepted Stay request precedes Protect's profile update. The old Disarmed
// read must keep the estimate visible and prevent duplicate Arm requests.
vm.runInContext("acceptObservation({...ready,pendingArmSeconds:59,remaining:null});",context);
assert.equal(body.dataset.alarmMode,'exit');
assert.equal(elements['countdown-value'].textContent,'0:59');
assert.equal(elements['arm-stay'].disabled,true);
assert.equal(vm.runInContext('confirmedDisarmed()',context),false);
assert.match(elements['alarm-detail'].textContent,/Confirming/);
now+=5000;
vm.runInContext("acceptObservation({...ready,pendingArmSeconds:54,remaining:null});",context);
assert.equal(elements['countdown-value'].textContent,'0:54');
vm.runInContext("acceptObservation({...ready,state:'arming',exitRemaining:53,pendingArmSeconds:0});",context);
assert.equal(elements['countdown-value'].textContent,'0:53');
assert.match(elements['alarm-detail'].textContent,/Leave and close/);
vm.runInContext("lock();acceptObservation({...ready,state:'armed',pendingArmSeconds:0});",context);
assert.equal(elements['sleep-state'].textContent,'Armed');
assert.equal(elements['standby-lock'].dataset.icon,'closed');
vm.runInContext("acceptObservation({...ready,pendingArmSeconds:0});",context);
assert.equal(elements['sleep-state'].textContent,'Disarmed');
assert.equal(elements['alarm-display'].hidden,true);
console.log('Accepted Stay request, confirmed exit timing, duplicate-arm prevention, and disarm checks passed.');
